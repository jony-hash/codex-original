def load_config(path: str | Path = DEFAULT_CONFIG_PATH) -> tuple[Path, dict[str, Any], str, str]:
    target = _resolve(path)
    payload = yaml.safe_load(target.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("prior shape decomposition config must be a mapping")
    _assert_config(payload)
    return target, payload, file_sha256(target), canonical_sha256(payload)


def _validate_rcr_a(config: Mapping[str, Any]) -> dict[str, Any]:
    binding = _require_mapping(config["rcr_a"], "rcr_a")
    config_path = _resolve(binding["config"])
    if file_sha256(config_path) != binding["config_sha256"]:
        raise ValueError("RCR-A config file hash does not match")
    loaded_path, rcr_config, file_hash, canonical_hash = rcr.load_replay_config(config_path)
    if loaded_path != config_path or file_hash != binding["config_sha256"] or canonical_hash != binding["config_canonical_sha256"]:
        raise ValueError("RCR-A config identity does not match")
    parent = rcr._validate_parent_mra(rcr_config)
    r2_identity = rcr._validate_r2(rcr_config)
    manifest_path = _resolve(binding["manifest"])
    metrics_path = _resolve(binding["metrics"])
    manifest = _load_json(manifest_path, expected_sha256=binding["manifest_sha256"])
    metrics = _load_json(metrics_path, expected_sha256=binding["metrics_sha256"])
    if manifest.get("schema") != rcr.REPLAY_MANIFEST_SCHEMA or manifest.get("task_id") != rcr.TASK_ID or manifest.get("status") != "completed" or manifest.get("gate") != rcr.MRA_PRIOR_CONTRACT_REVIEW_REQUIRED:
        raise ValueError("RCR-A manifest status or schema is invalid")
    if manifest.get("next_action") != "PLAN_PRIOR_SHAPE_CONTRACT_REVIEW":
        raise ValueError("RCR-A next-action binding is invalid")
    if metrics.get("schema") != rcr.METRICS_SCHEMA or metrics.get("task_id") != rcr.TASK_ID or metrics.get("status") != "completed" or metrics.get("gate") != rcr.MRA_PRIOR_CONTRACT_REVIEW_REQUIRED:
        raise ValueError("RCR-A metrics status or schema is invalid")
    if metrics.get("learned_state_freeze", {}).get("state_unchanged") is not True or metrics.get("learned_state_freeze", {}).get("decoder_entered") is not False:
        raise ValueError("RCR-A learned-state or decoder boundary is invalid")
    if metrics.get("calibration", {}).get("new", {}).get("sha256") != config["r2_calibration"]["payload_sha256"]:
        raise ValueError("RCR-A does not bind the configured repaired calibration")
    return {
        "config_path": config_path,
        "config": rcr_config,
        "config_sha256": file_hash,
        "config_canonical_sha256": canonical_hash,
        "parent": parent,
        "r2": r2_identity,
        "manifest_path": manifest_path,
        "manifest": manifest,
        "metrics_path": metrics_path,
        "metrics": metrics,
    }


def _resource_preflight(config: Mapping[str, Any], output_path: Path) -> tuple[int, int, int]:
    execution = _require_mapping(config["execution"], "execution")
    if os.environ.get("CUBLAS_WORKSPACE_CONFIG") != execution["require_cublas_workspace_config"]:
        raise RuntimeError("BLOCKED_REPLAY_ENVIRONMENT: CUBLAS_WORKSPACE_CONFIG must be :4096:8")
    device = torch.device(execution["device"])
    if device.type != "cuda" or not torch.cuda.is_available():
        raise RuntimeError("BLOCKED_CUDA_UNAVAILABLE")
    free, total = torch.cuda.mem_get_info(device)
    if free < execution["min_free_cuda_bytes"]:
        raise RuntimeError("BLOCKED_REPLAY_RESOURCE: less than 4 GiB free CUDA memory")
    disk = shutil.disk_usage(base._repo_root().anchor or str(base._repo_root()))
    if disk.free < execution["min_disk_free_bytes"]:
        raise RuntimeError("BLOCKED_REPLAY_RESOURCE: less than 10 GiB free disk")
    if output_path.exists():
        raise FileExistsError(f"write-once output already exists: {_relative_path(output_path)}")
    return int(free), int(total), int(disk.free)


