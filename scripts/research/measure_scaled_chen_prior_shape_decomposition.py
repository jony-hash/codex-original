def next_write_once_output(base_path: str | Path) -> Path:
    """Return the first unused numbered output without touching the disk."""
    requested = Path(base_path)
    match = re.fullmatch(r"(.+)_attempt_(\d+)", requested.name)
    if match is None:
        raise ValueError("write-once output must end with _attempt_<number>")
    prefix, number_text = match.groups()
    number = int(number_text)
    while True:
        candidate = requested.parent / f"{prefix}_attempt_{number:02d}"
        if not candidate.exists():
            return candidate
        number += 1


def _summary_vector(value: torch.Tensor) -> dict[str, float]:
    view = value.detach().to(torch.float64).cpu().reshape(-1)
    if view.numel() == 0 or not torch.isfinite(view).all():
        raise ValueError("summary vector must be finite and non-empty")
    quantiles = torch.quantile(view, torch.tensor([0.05, 0.50, 0.95], dtype=torch.float64))
    return {
        "min": float(view.min()),
        "p5": float(quantiles[0]),
        "median": float(quantiles[1]),
        "mean": float(view.mean()),
        "p95": float(quantiles[2]),
        "max": float(view.max()),
    }


def _validate_latent(z: torch.Tensor) -> torch.Tensor:
    if z.ndim != 2 or z.shape[1] != LATENT_DIM:
        raise ValueError("latent matrix must have shape [N,100]")
    if z.shape[0] < 2 or not torch.is_floating_point(z) or torch.is_complex(z):
        raise ValueError("latent matrix must be real floating-point data with >=2 rows")
    if not torch.isfinite(z).all() or (z < 0).any():
        raise ValueError("latent matrix must be finite and non-negative")
    return z.detach().to(torch.float64).cpu().contiguous()


def theoretical_truncated_normal(
    *, mean: float = 1.0, variance: float = 0.25, lower: float = 0.0
) -> dict[str, Any]:
    """Return exact moments and quantiles for Normal(mean, variance)|X>=lower."""
    if not all(math.isfinite(value) for value in (mean, variance, lower)) or variance <= 0.0:
        raise ValueError("truncated-normal parameters are invalid")
    sigma = math.sqrt(variance)
    alpha = (lower - mean) / sigma
    normal = NormalDist()
    survival = 1.0 - normal.cdf(alpha)
    if survival <= 0.0:
        raise ValueError("truncated-normal survival probability is zero")
    phi = math.exp(-0.5 * alpha * alpha) / math.sqrt(2.0 * math.pi)
    lam = phi / survival
    ey = lam
    ey2 = 1.0 + alpha * lam
    ey3 = (alpha * alpha + 2.0) * lam
    ex = mean + sigma * ey
    ex2 = mean * mean + 2.0 * mean * sigma * ey + variance * ey2
    ex3 = (
        mean**3
        + 3.0 * mean * mean * sigma * ey
        + 3.0 * mean * variance * ey2
        + sigma**3 * ey3
    )
    central_variance = ex2 - ex * ex
    central_third = ex3 - 3.0 * ex * ex2 + 2.0 * ex**3
    probabilities = QUANTILE_PROBABILITIES
    quantiles = [
        mean + sigma * normal.inv_cdf(normal.cdf(alpha) + probability * survival)
        for probability in probabilities
    ]
    return {
        "mean": ex,
        "variance": central_variance,
        "skew": central_third / central_variance ** 1.5,
        "quantiles": quantiles,
        "lower": lower,
        "base_mean": mean,
        "base_variance": variance,
        "standard_deviation": sigma,
        "survival_at_lower": survival,
        "mills_ratio": lam,
    }


def sample_registered_prior(
    count: int,
    *,
    seed: int,
    mean: float = 1.0,
    variance: float = 0.25,
    lower: float = 0.0,
) -> torch.Tensor:
    if count <= 0:
        raise ValueError("prior sample count must be positive")
    if lower != 0.0:
        raise ValueError("the registered sampler has lower bound zero")
    generator = torch.Generator(device="cpu").manual_seed(seed)
    result = bogt.truncated_normal_sample(
        (count, LATENT_DIM),
        generator=generator,
        mean=mean,
        variance=variance,
        device="cpu",
        dtype=torch.float32,
    )
    return _validate_latent(result)


def tail_masses(z: torch.Tensor, prior_quantiles: Sequence[float]) -> dict[str, torch.Tensor]:
    view = _validate_latent(z)
    thresholds = tuple(float(value) for value in prior_quantiles)
    if len(thresholds) != 4 or tuple(sorted(thresholds)) != thresholds:
        raise ValueError("prior quantiles must be four sorted thresholds")
    q01, _, q95, q99 = thresholds
    return {
        "lower": (view < q01).to(torch.float64).mean(dim=0),
        "upper": (view > q99).to(torch.float64).mean(dim=0),
        "central": ((view >= q01) & (view <= q99)).to(torch.float64).mean(dim=0),
        "q95_exceedance": (view > q95).to(torch.float64).mean(dim=0),
    }


def summarize_port_statistics(
    z: torch.Tensor, *, prior: Mapping[str, Any]
) -> dict[str, Any]:
    view = _validate_latent(z)
    mean = view.mean(dim=0)
    variance = view.var(dim=0, unbiased=False)
    quantile_tensor = torch.quantile(
        view,
        torch.tensor(QUANTILE_PROBABILITIES, dtype=torch.float64),
        dim=0,
    ).transpose(0, 1).contiguous()
    prior_quantiles = tuple(float(value) for value in prior["quantiles"])
    tails = tail_masses(view, prior_quantiles)
    variance_ratio = variance / float(prior["variance"])
    return {
        "sample_count": int(view.shape[0]),
        "port_count": int(view.shape[1]),
        "mean": mean,
        "variance": variance,
        "delta_to_prior_mean": mean - float(prior["mean"]),
        "variance_ratio_to_prior": variance_ratio,
        "quantiles": quantile_tensor,
        "tails": tails,
        "mean_summary": _summary_vector(mean),
        "variance_summary": _summary_vector(variance),
        "variance_ratio_summary": _summary_vector(variance_ratio),
        "tail_summaries": {
            name: _summary_vector(value) for name, value in tails.items()
        },
        "mean_heterogeneity_std": float(mean.std(unbiased=False)),
        "mean_heterogeneity_range": float(mean.max() - mean.min()),
        "variance_heterogeneity_std": float(variance.std(unbiased=False)),
        "variance_heterogeneity_range": float(variance.max() - variance.min()),
    }


def mean_variance_decomposition(
    z: torch.Tensor, mean: torch.Tensor | None = None, variance: torch.Tensor | None = None
) -> dict[str, float]:
    view = _validate_latent(z)
    mean_value = view.mean(dim=0) if mean is None else mean.detach().to(torch.float64).cpu()
    variance_value = (
        view.var(dim=0, unbiased=False)
        if variance is None
        else variance.detach().to(torch.float64).cpu()
    )
    if mean_value.shape != (LATENT_DIM,) or variance_value.shape != (LATENT_DIM,):
        raise ValueError("decomposition vectors must have shape [100]")
    within = variance_value.mean()
    between = mean_value.var(unbiased=False)
    total = view.var(unbiased=False)
    identity_residual = total - within - between
    return {
        "within": float(within),
        "between": float(between),
        "total": float(total),
        "identity_residual": float(identity_residual),
        "within_fraction": float(within / total) if total > 0 else 0.0,
        "between_fraction": float(between / total) if total > 0 else 0.0,
    }


def covariance_and_correlation(z: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
    view = _validate_latent(z)
    centered = view - view.mean(dim=0, keepdim=True)
    covariance = centered.transpose(0, 1).matmul(centered) / view.shape[0]
    diagonal = torch.diagonal(covariance)
    if (diagonal <= 0).any() or not torch.isfinite(covariance).all():
        raise ValueError("covariance diagonal must be finite and positive")
    correlation = covariance / torch.sqrt(diagonal[:, None] * diagonal[None, :])
    if not torch.isfinite(correlation).all():
        raise ValueError("correlation matrix is non-finite")
    return covariance.contiguous(), correlation.contiguous()


def dependence_summaries(
    covariance: torch.Tensor, correlation: torch.Tensor
) -> dict[str, Any]:
    if covariance.shape != (LATENT_DIM, LATENT_DIM) or correlation.shape != covariance.shape:
        raise ValueError("covariance and correlation must be [100,100]")
    mask = ~torch.eye(LATENT_DIM, dtype=torch.bool)
    abs_offdiag = correlation.detach().to(torch.float64).abs()[mask]
    offdiag_cov = covariance.detach().to(torch.float64)[mask]
    offdiag_energy = float(offdiag_cov.square().sum())
    total_energy = float(covariance.detach().to(torch.float64).square().sum())
    if total_energy <= 0.0:
        raise ValueError("total covariance energy must be positive")
    eigenvalues = torch.linalg.eigvalsh(covariance.detach().to(torch.float64)).flip(0)
    positive_eigenvalues = eigenvalues.clamp_min(0.0)
    trace = float(positive_eigenvalues.sum())
    eigen_energy = float(positive_eigenvalues.square().sum())
    effective_rank = trace * trace / eigen_energy if eigen_energy > 0.0 else 0.0
    return {
        "mean_abs_off_diagonal_correlation": float(abs_offdiag.mean()),
        "median_abs_off_diagonal_correlation": float(torch.quantile(abs_offdiag, 0.50)),
        "p95_abs_off_diagonal_correlation": float(torch.quantile(abs_offdiag, 0.95)),
        "max_abs_off_diagonal_correlation": float(abs_offdiag.max()),
        "off_diagonal_covariance_energy": offdiag_energy,
        "total_covariance_energy": total_energy,
        "off_diagonal_covariance_fraction": offdiag_energy / total_energy,
        "covariance_eigenvalues": [float(value) for value in positive_eigenvalues],
        "covariance_effective_rank": effective_rank,
    }


def _append_quantile_replica_scalars(
    statistics: dict[str, list[float]], quantiles: torch.Tensor
) -> None:
    for index, name in enumerate(QUANTILE_NAMES):
        vector = quantiles[:, index]
        statistics[f"{name}_port_mean"].append(float(vector.mean()))
        statistics[f"{name}_port_median"].append(float(torch.quantile(vector, 0.50)))
        statistics[f"{name}_port_std"].append(float(vector.std(unbiased=False)))


def prior_null_replicates(
    *,
    sample_count: int,
    replicates: int,
    seed: int,
    quantiles: Sequence[float],
) -> dict[str, Any]:
    """Generate matched-size independent-prior scalar summaries only."""
    if sample_count < 2 or replicates <= 0:
        raise ValueError("prior-null sample count and replicate count must be positive")
    prior = {"mean": 1.027623931339495, "variance": 0.2216129870778559, "quantiles": list(quantiles)}
    generator = torch.Generator(device="cpu").manual_seed(seed)
    statistic_names = list(PRIOR_NULL_STAT_NAMES)
    statistic_names.extend(
        f"{quantile_name}_port_{summary_name}"
        for quantile_name in QUANTILE_NAMES
        for summary_name in ("mean", "median", "std")
    )
    values = {name: [] for name in statistic_names}
    for _ in range(replicates):
        sample = bogt.truncated_normal_sample(
            (sample_count, LATENT_DIM),
            generator=generator,
            device="cpu",
            dtype=torch.float32,
        )
        statistics = summarize_port_statistics(sample, prior=prior)
        covariance, correlation = covariance_and_correlation(sample)
        dependence = dependence_summaries(covariance, correlation)
        tails = statistics["tails"]
        tail_deviation = float(
            (tails["lower"] - 0.01).abs().mean()
            + (tails["upper"] - 0.01).abs().mean()
        )
        scalar_values = {
            "mean_heterogeneity_std": statistics["mean_heterogeneity_std"],
            "mean_heterogeneity_range": statistics["mean_heterogeneity_range"],
            "variance_heterogeneity_std": statistics["variance_heterogeneity_std"],
            "variance_heterogeneity_range": statistics["variance_heterogeneity_range"],
            **{
                name: dependence[name]
                for name in (
                    "mean_abs_off_diagonal_correlation",
                    "median_abs_off_diagonal_correlation",
                    "p95_abs_off_diagonal_correlation",
                    "max_abs_off_diagonal_correlation",
                    "off_diagonal_covariance_energy",
                    "total_covariance_energy",
                    "off_diagonal_covariance_fraction",
                )
            },
            "tail_deviation": tail_deviation,
            "lower_tail_mass_mean": float(tails["lower"].mean()),
            "upper_tail_mass_mean": float(tails["upper"].mean()),
            "central_mass_mean": float(tails["central"].mean()),
            "q95_exceedance_mean": float(tails["q95_exceedance"].mean()),
        }
        for name, value in scalar_values.items():
            values[name].append(float(value))
        _append_quantile_replica_scalars(values, statistics["quantiles"])
        del sample, covariance, correlation
    return {
        "schema": NULL_SCHEMA,
        "sample_count": sample_count,
        "replicate_count": replicates,
        "seed": seed,
        "sampler": "bogt.truncated_normal_sample_inverse_cdf",
        "factorized": True,
        "saved_replica_samples": False,
        "statistics": values,
    }


def _compare_observed_to_null(
    observed: float, null_values: Sequence[float], *, central_interval: float
) -> dict[str, Any]:
    if not null_values or not math.isfinite(observed):
        raise ValueError("observed and null statistics must be finite")
    values = torch.tensor(null_values, dtype=torch.float64)
    tail = (1.0 - central_interval) / 2.0
    interval = torch.quantile(values, torch.tensor([tail, 1.0 - tail], dtype=torch.float64))
    percentile = float((values <= observed).to(torch.float64).mean() * 100.0)
    return {
        "observed": observed,
        "prior_reference_median": float(torch.quantile(values, 0.50)),
        "prior_reference_central_interval": [float(interval[0]), float(interval[1])],
        "prior_reference_percentile_position": percentile,
        "outside_lower": observed < float(interval[0]),
        "outside_upper": observed > float(interval[1]),
        "central_interval": central_interval,
    }


def classify_structure(
    evidence_by_split: Mapping[str, Mapping[str, Any]], name: str = "P-S3"
) -> tuple[str, str]:
    if set(evidence_by_split) != set(SPLITS):
        raise ValueError("structure evidence must contain selection and confirmation")
    upper = [bool(evidence_by_split[split]["outside_upper"]) for split in SPLITS]
    if all(upper):
        return f"{name}_SUPPORTED", "REPLICATED_DIRECTION"
    if any(upper):
        return "PANEL_SPECIFIC", "PANEL_SPECIFIC"
    return "WEAK_OR_NULL", "WEAK_OR_NULL"


def classify_pcr(
    *,
    contract_sanity: bool,
    coordinate_consistent: bool,
    observer_complete: bool,
    panel_interpretable: bool,
) -> str:
    if not contract_sanity:
        return PCR2
    if not coordinate_consistent:
        return PCR3
    if not observer_complete or not panel_interpretable:
        return PCR4
    return PCR1


def validate_panel_mapping(
    panels: Mapping[str, torch.Tensor], *, selection_count: int, confirmation_count: int
) -> None:
    if set(panels) != set(SPLITS):
        raise ValueError("panel mapping must contain selection and confirmation")
    expected = {"selection": selection_count, "confirmation": confirmation_count}
    for split, value in panels.items():
        if not torch.is_tensor(value) or tuple(value.shape) != (expected[split], LATENT_DIM):
            raise ValueError(f"{split} panel mapping has the wrong shape")


